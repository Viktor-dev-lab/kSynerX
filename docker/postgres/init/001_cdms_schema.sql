-- PostgreSQL translation of the supplied CDMS DBML.
-- Run once against a fresh database. The entire schema is atomic.
BEGIN;

SET LOCAL search_path TO public;

CREATE TYPE channel_type AS ENUM ('POLLING', 'WEBHOOK', 'EXCEL');
CREATE TYPE inbox_status AS ENUM (
    'PENDING', 'RETRY', 'APPLIED', 'STALE', 'DUPLICATE', 'CONFLICT', 'FAILED'
);

CREATE TABLE products (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_code varchar(100) NOT NULL,
    product_id bigint NOT NULL,
    product_name text,
    sku text,
    partner_sku text,
    outbound_type varchar(50),
    is_expiry_date boolean,
    is_attribute boolean,
    is_lot_number boolean,
    is_tracking_serial boolean,
    num_days_warning_exp_date integer,
    num_days_export_before_exp_date integer,
    packing_note text,
    avatar_url text,
    asset_type varchar(50),
    is_physical boolean,
    has_serial boolean,
    color text,
    size text,
    description text,
    is_active boolean,
    is_discreet boolean,
    parent_partner_sku text,
    hs_code text,
    country_of_origin text,
    ref_code text,
    revision bigint NOT NULL,
    content_hash varchar(64) NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT uq_products_source_product UNIQUE (source_code, product_id),
    CONSTRAINT chk_products_revision CHECK (revision > 0),
    CONSTRAINT chk_products_content_hash CHECK (content_hash ~ '^[0-9a-f]{64}$')
);

CREATE INDEX idx_products_source_sku ON products (source_code, sku);
CREATE INDEX idx_products_source_partner_sku ON products (source_code, partner_sku);

CREATE TABLE product_units (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_record_id bigint NOT NULL,
    position integer NOT NULL,
    unit_code text,
    unit_name text,
    length numeric,
    width numeric,
    height numeric,
    weight numeric,
    CONSTRAINT uq_product_units_position UNIQUE (product_record_id, position),
    CONSTRAINT chk_product_units_position CHECK (position >= 0),
    CONSTRAINT fk_product_units_product FOREIGN KEY (product_record_id)
        REFERENCES products (id) ON DELETE CASCADE
);

CREATE TABLE product_categories (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_record_id bigint NOT NULL,
    position integer NOT NULL,
    category_code text,
    category_name text,
    CONSTRAINT uq_product_categories_position UNIQUE (product_record_id, position),
    CONSTRAINT chk_product_categories_position CHECK (position >= 0),
    CONSTRAINT fk_product_categories_product FOREIGN KEY (product_record_id)
        REFERENCES products (id) ON DELETE CASCADE
);

CREATE TABLE product_bundles (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_record_id bigint NOT NULL,
    position integer NOT NULL,
    sku text,
    unit_code text,
    qty numeric,
    available_percentage numeric,
    CONSTRAINT uq_product_bundles_position UNIQUE (product_record_id, position),
    CONSTRAINT chk_product_bundles_position CHECK (position >= 0),
    CONSTRAINT fk_product_bundles_product FOREIGN KEY (product_record_id)
        REFERENCES products (id) ON DELETE CASCADE
);

CREATE TABLE product_bundle_details (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_bundle_id bigint NOT NULL,
    position integer NOT NULL,
    qty numeric,
    sale_price numeric,
    CONSTRAINT uq_product_bundle_details_position UNIQUE (product_bundle_id, position),
    CONSTRAINT chk_product_bundle_details_position CHECK (position >= 0),
    CONSTRAINT fk_product_bundle_details_bundle FOREIGN KEY (product_bundle_id)
        REFERENCES product_bundles (id) ON DELETE CASCADE
);

CREATE TABLE product_barcodes (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_record_id bigint NOT NULL,
    position integer NOT NULL,
    barcode_product_id bigint,
    product_name text,
    sku text,
    partner_sku text,
    CONSTRAINT uq_product_barcodes_position UNIQUE (product_record_id, position),
    CONSTRAINT chk_product_barcodes_position CHECK (position >= 0),
    CONSTRAINT fk_product_barcodes_product FOREIGN KEY (product_record_id)
        REFERENCES products (id) ON DELETE CASCADE
);

CREATE TABLE channels (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_code varchar(100) NOT NULL DEFAULT 'VIETFUL_DEMO',
    type channel_type NOT NULL UNIQUE,
    enabled boolean NOT NULL DEFAULT true,
    poll_interval_seconds integer,
    created_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT chk_channels_poll_interval CHECK (
        poll_interval_seconds IS NULL OR poll_interval_seconds > 0
    )
);

CREATE TABLE inbox_events (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    channel_id bigint NOT NULL,
    product_id bigint NOT NULL,
    revision bigint NOT NULL,
    payload jsonb NOT NULL,
    content_hash varchar(64) NOT NULL,
    status inbox_status NOT NULL DEFAULT 'PENDING',
    retry_count integer NOT NULL DEFAULT 0,
    next_retry_at timestamptz NOT NULL DEFAULT now(),
    error_message text,
    created_at timestamptz NOT NULL DEFAULT now(),
    processed_at timestamptz,
    CONSTRAINT chk_inbox_revision CHECK (revision > 0),
    CONSTRAINT chk_inbox_retry_count CHECK (retry_count >= 0),
    CONSTRAINT chk_inbox_payload_object CHECK (jsonb_typeof(payload) = 'object'),
    CONSTRAINT chk_inbox_content_hash CHECK (content_hash ~ '^[0-9a-f]{64}$'),
    CONSTRAINT fk_inbox_events_channel FOREIGN KEY (channel_id)
        REFERENCES channels (id) ON DELETE RESTRICT
);

CREATE INDEX idx_inbox_worker_pick ON inbox_events (status, next_retry_at, created_at);
CREATE INDEX idx_inbox_channel_product ON inbox_events (channel_id, product_id);

COMMENT ON TABLE products IS
    'Latest normalized product snapshot per logical source. Commit product, children and inbox outcome in one transaction.';
COMMENT ON COLUMN products.id IS 'Internal database ID referenced by child tables.';
COMMENT ON COLUMN products.source_code IS 'Logical source shared across its POLLING, WEBHOOK and EXCEL channels.';
COMMENT ON COLUMN products.product_id IS 'External productId from the source API.';
COMMENT ON COLUMN products.parent_partner_sku IS 'External source value; intentionally no FK because the parent may not have been ingested.';
COMMENT ON COLUMN products.revision IS 'Latest source revision observed, including revisions with unchanged business content.';
COMMENT ON COLUMN products.content_hash IS 'SHA-256 of consistently normalized canonical business content including ordered child collections; excludes revision and local metadata. Use one null-versus-empty collection policy across channels.';
COMMENT ON COLUMN products.updated_at IS 'CDMS write time, set explicitly on updates. Not a source ordering field; no automatic update trigger.';
COMMENT ON COLUMN product_units.position IS 'Zero-based position in the units array.';
COMMENT ON COLUMN product_categories.position IS 'Zero-based position in the categories array.';
COMMENT ON COLUMN product_bundles.position IS 'Zero-based position in the bundles array.';
COMMENT ON COLUMN product_bundle_details.position IS 'Zero-based position in the bundle detail array.';
COMMENT ON COLUMN product_barcodes.position IS 'Zero-based position in the barcodes array.';
COMMENT ON TABLE product_categories IS 'Product-scoped category snapshot, not a shared category master.';
COMMENT ON COLUMN product_barcodes.barcode_product_id IS 'External productId inside productBarcodes, not the parent FK.';
COMMENT ON COLUMN channels.source_code IS 'Same logical source across its three channels; application must keep immutable once events exist.';
COMMENT ON COLUMN channels.type IS 'Prototype allows one configured channel per type.';
COMMENT ON COLUMN channels.poll_interval_seconds IS 'Polling interval; application should leave NULL for WEBHOOK and EXCEL. Other settings live in application.yaml.';
COMMENT ON COLUMN inbox_events.product_id IS 'External productId; intentionally no FK because the product may not exist yet.';
COMMENT ON COLUMN inbox_events.revision IS 'Source revision preserved across all channels, generated atomically by the inventory emulator.';
COMMENT ON COLUMN inbox_events.payload IS 'Complete, consistently normalized Product detail snapshot. Object shape is checked here; completeness is validated by the application.';
COMMENT ON COLUMN inbox_events.content_hash IS 'Canonical business-content hash using the same algorithm as products.';
COMMENT ON COLUMN inbox_events.error_message IS 'Failure reason or conflict details.';
COMMENT ON TABLE inbox_events IS
    'Workers select eligible PENDING/RETRY events FOR UPDATE SKIP LOCKED. Keep inbox lock, product and child writes, and final status in one short transaction. No separately committed PROCESSING state. APPLIED, STALE, DUPLICATE, CONFLICT and FAILED are terminal. Record retry metadata after rolling back failed processing. Repeated deliveries may create multiple rows; product writes are idempotent through source/product unique key, revision and content hash. No per-file checkpoints; failed reads/imports may be replayed if the source or original file remains available.';

COMMIT;
